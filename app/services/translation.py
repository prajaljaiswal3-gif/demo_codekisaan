def get_text(key, lang="mr", default=None):
    """Retrieves translation for a key in specified language. Falls back to English, then default."""
    if key in TRANSLATIONS:
        return TRANSLATIONS[key].get(lang, TRANSLATIONS[key].get("en", default or key))
    return default or key

def get_all_translations(lang="mr"):
    """Returns a flat dictionary of all keys localized to requested language."""
    return {k: v.get(lang, v.get("en", k)) for k, v in TRANSLATIONS.items()}
